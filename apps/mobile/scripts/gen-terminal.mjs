// Builds the page the app's terminal runs in: xterm, its two add-ons and the bridge, as one HTML
// document in a string the app can hand to a web view. Run with `pnpm gen:terminal` after changing
// `terminal-bridge.js` or upgrading xterm; the result is committed, so a build needs nothing else.
//
// xterm comes from the desktop's install (`packages/client`), so both apps draw with one version.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const client = createRequire(resolve(here, '../../../packages/client/package.json'))
const read = (name) => readFileSync(client.resolve(name), 'utf8')
// A closing script tag inside a script would end it early.
const script = (source) => `<script>${source.replaceAll('</script', '<\\/script')}</script>`

const page = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${read('@xterm/xterm/css/xterm.css')}</style>
<style>
html, body { height: 100%; margin: 0; background: __BACKGROUND__; overflow: hidden; }
#terminal { position: absolute; top: 0; right: 0; bottom: 0; left: 0; padding: 6px; }
.xterm-viewport { overflow-y: auto !important; }
</style>
</head>
<body>
<div id="terminal"></div>
${script(read('@xterm/xterm/lib/xterm.js'))}
${script(read('@xterm/addon-fit/lib/addon-fit.js'))}
${script(read('@xterm/addon-unicode11/lib/addon-unicode11.js'))}
${script(readFileSync(resolve(here, 'terminal-bridge.js'), 'utf8'))}
</body>
</html>
`

const version = client('@xterm/xterm/package.json').version
const out = resolve(here, '../src/components/terminal/page.generated.ts')
writeFileSync(
  out,
  `// Generated by scripts/gen-terminal.mjs (xterm ${version}). Do not edit: run \`pnpm gen:terminal\`.\n` +
    `export const TERMINAL_PAGE = ${JSON.stringify(page)}\n`,
)
console.log(`wrote ${out} (${Math.round(page.length / 1024)} KB, xterm ${version})`)
